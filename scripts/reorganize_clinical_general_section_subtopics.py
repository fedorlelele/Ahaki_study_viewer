def normalize(text: str) -> str:
    text = (text or "").replace("\n", " ").replace("\u3000", " ").lower()
    while "  " in text:
        text = text.replace("  ", " ")
    return text


def choose_by_rules(text: str, rules: list[tuple[str, list[str]]], default: str):
    for label, patterns in rules:
        hits = [pattern for pattern in patterns if normalize(pattern) in text]
        if hits:
            return label, f"match:{', '.join(hits[:4])}", "high"
    return default, "default", "medium"


