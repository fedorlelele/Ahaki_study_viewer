def classify_subtopic(section: str, stem: str, choices: str):
    text = normalize(f"{stem} {choices}")
    if section == HOLDOUT:
        return choose_by_rules(text, HOLDOUT_RULES, "保留：各論疾患知識")
    config = SECTION_RULES.get(section)
    if not config:
        return "未整理", "default", "low"
    return choose_by_rules(text, config["rules"], config["default"])


def main():
    with INPUT_CSV.open(encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    output_rows = []
    review_rows = []
    for row in rows:
        subtopic, subreason, subconf = classify_subtopic(
            row["textbook_section"], row.get("stem", ""), row.get("choices", "")
        )
        new_row = {
            "serial": row["serial"],
            "exam_type": row["exam_type"],
            "exam_session": row["exam_session"],
            "current_subtopics": row["current_subtopics"],
            "textbook_section": row["textbook_section"],
            "section_subtopic": subtopic,
            "distribution_status": row["distribution_status"],
            "section_confidence": row["confidence"],
            "subtopic_confidence": subconf,
            "section_reason": row["reason"],
            "subtopic_reason": subreason,
            "stem": row["stem"],
            "choices": row["choices"],
        }
        output_rows.append(new_row)
        if subconf != "high":
            review_rows.append(new_row)

    with OUTPUT_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "serial",
                "exam_type",
                "exam_session",
                "current_subtopics",
                "textbook_section",
                "section_subtopic",
                "distribution_status",
                "section_confidence",
                "subtopic_confidence",
                "section_reason",
                "subtopic_reason",
                "stem",
                "choices",
            ],
        )
        writer.writeheader()
        writer.writerows(output_rows)

    with REVIEW_CSV.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(output_rows[0].keys()))
        writer.writeheader()
        writer.writerows(review_rows)

    section_counts = Counter(row["textbook_section"] for row in output_rows)
    section_subtopic_counts = defaultdict(Counter)
    for row in output_rows:
        section_subtopic_counts[row["textbook_section"]][row["section_subtopic"]] += 1

    lines = [
        "# 臨床医学総論 再編サマリー",
        "",
        f"入力CSV: `{INPUT_CSV}`",
        f"出力CSV: `{OUTPUT_CSV}`",
        f"要確認CSV: `{REVIEW_CSV}`",
        "",
        f"総問題数: {len(output_rows)}",
        "",
        "## 節別件数",
        "",
    ]
    for section, count in section_counts.most_common():
        lines.append(f"- {section}: {count}問")
    for section, counter in section_subtopic_counts.items():
        lines.extend(["", f"## {section}", ""])
        for subtopic, count in counter.most_common():
            lines.append(f"- {subtopic}: {count}問")
    large = [
        (section, subtopic, count)
        for section, counter in section_subtopic_counts.items()
        for subtopic, count in counter.items()
        if count > 40
    ]
    lines.extend(["", "## 40問超の細分類", ""])
    if large:
        for section, subtopic, count in sorted(large, key=lambda item: item[2], reverse=True):
            lines.append(f"- {section} / {subtopic}: {count}問")
    else:
        lines.append("- なし")

    SUMMARY_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
